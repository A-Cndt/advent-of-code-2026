def build_user_agent() -> str:
    """Build the User-Agent header sent to adventofcode.com.

    :return: the base identifier, followed by the contact details found in
        the ``AOC_CONTACT`` environment variable (if any)
    :rtype: str
    """
    contact = os.environ.get("AOC_CONTACT", "").strip()
    return f"{USER_AGENT_BASE} ({contact})" if contact else USER_AGENT_BASE


def http_get(url: str, session: str = "") -> str:
    """Perform a GET request on adventofcode.com.

    :param url: full URL to query
    :type url: str
    :param session: session cookie (optional for the puzzle page)
    :type session: str
    :return: response body decoded as UTF-8
    :rtype: str
    :raises AocError: on HTTP or network errors
    """
    headers = {"User-Agent": build_user_agent()}
    if session:
        headers["Cookie"] = f"session={session}"
    request = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return response.read().decode("utf-8")
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise AocError("Jour introuvable ou pas encore débloqué.") from exc
        if exc.code in (400, 401, 403, 500):
            raise AocError(
                "Accès refusé : cookie de session invalide ou expiré."
            ) from exc
        raise AocError(f"Erreur HTTP {exc.code}.") from exc
    except urllib.error.URLError as exc:
        raise AocError(f"Erreur réseau : {exc.reason}") from exc


class PuzzleParser(HTMLParser):
    """Extract the title and the ``<pre>`` blocks of a puzzle page.

    The ``<pre>`` blocks contain the examples (and sometimes other
    illustrations): the user then picks the one that fits.
    """

    def __init__(self) -> None:
        """Initialize the parser and its internal buffers."""
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.blocks: list[str] = []
        self._in_pre = False
        self._in_h2 = False
        self._pre_buffer: list[str] = []
        self._h2_buffer: list[str] = []

    def handle_starttag(self, tag: str, attrs: list) -> None:
        """Open a buffer when entering a ``pre`` or ``h2`` tag."""
        if tag == "pre":
            self._in_pre, self._pre_buffer = True, []
        elif tag == "h2":
            self._in_h2, self._h2_buffer = True, []

    def handle_endtag(self, tag: str) -> None:
        """Commit the buffer content when the tag is closed."""
        if tag == "pre" and self._in_pre:
            self._in_pre = False
            block = "".join(self._pre_buffer).strip("\n")
            if block:
                self.blocks.append(block + "\n")
        elif tag == "h2" and self._in_h2:
            self._in_h2 = False
            text = "".join(self._h2_buffer).strip()
            # The title looks like "--- Day 1: Some Title ---"
            if not self.title and ":" in text:
                self.title = text.strip("- ").strip()

    def handle_data(self, data: str) -> None:
        """Feed the buffers with the text found between the tags."""
        if self._in_pre:
            self._pre_buffer.append(data)
        if self._in_h2:
            self._h2_buffer.append(data)


def parse_puzzle(page: str) -> tuple[str, list[str]]:
    """Parse a puzzle page.

    :param page: HTML source of the page
    :type page: str
    :return: the title of the day and the list of code blocks found
    :rtype: tuple[str, list[str]]
    """
    parser = PuzzleParser()
    parser.feed(page)
    return parser.title, parser.blocks


