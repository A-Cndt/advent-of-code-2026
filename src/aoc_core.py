def run_solution(
    day: int, part: int, raw_data: str
) -> tuple[Any, float, str]:
    """Load the ``solution.py`` of a day and run the requested part.

    The module is reloaded on every call, so your edits are taken into
    account without restarting the application.

    :param day: day number
    :type day: int
    :param part: part to run (1 or 2)
    :type part: int
    :param raw_data: raw content (example or input) passed to the function
    :type raw_data: str
    :return: the result, the duration in seconds and the captured stdout
    :rtype: tuple[Any, float, str]
    :raises AttributeError: if the ``partN`` function does not exist
    """
    path = day_dir(day) / SOLUTION_FILE
    spec = importlib.util.spec_from_file_location(f"aoc_day{day:02d}", path)
    module = importlib.util.module_from_spec(spec)

    # Lets solution.py import helper modules located in its own folder.
    sys.path.insert(0, str(path.parent))
    try:
        spec.loader.exec_module(module)
        function: Callable | None = getattr(module, f"part{part}", None)
        if function is None:
            raise AttributeError(f"La fonction part{part}() est introuvable.")

        captured = io.StringIO()
        start = time.perf_counter()
        with redirect_stdout(captured):
            result = function(raw_data)
        elapsed = time.perf_counter() - start
    finally:
        sys.path.remove(str(path.parent))

    return result, elapsed, captured.getvalue()
