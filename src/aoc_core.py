def run_solution(
    day: int,
    part: int,
    raw_data: str,
) -> tuple[Any, float, str]:
    """Load and run the requested part of a day's solution.

    The module is loaded on every call so that edits are taken into account
    without restarting the application.

    :param day: day number
    :param part: puzzle part (1 or 2)
    :param raw_data: raw content passed to the solution
    :return: result, execution duration and captured stdout
    :raises ValueError: if the day or part is invalid
    :raises ImportError: if the solution module cannot be loaded
    :raises AttributeError: if the requested part does not exist
    """
    if not 1 <= day <= 25:
        raise ValueError("Le jour doit être compris entre 1 et 25.")

    if part not in (1, 2):
        raise ValueError("La partie doit être égale à 1 ou 2.")

    path = day_dir(day) / SOLUTION_FILE

    if not path.is_file():
        raise FileNotFoundError(
            f"Fichier de solution introuvable : {path}"
        )

    spec = importlib.util.spec_from_file_location(
        f"aoc_day{day:02d}",
        path,
    )

    if spec is None or spec.loader is None:
        raise ImportError(
            f"Impossible de charger le module de solution : {path}"
        )

    module: ModuleType = importlib.util.module_from_spec(spec)

    # Allow solution.py to import helper modules from its own directory.
    module_path = str(path.parent)
    sys.path.insert(0, module_path)

    try:
        spec.loader.exec_module(module)

        function: Callable[[str], Any] | None = getattr(
            module,
            f"part{part}",
            None,
        )

        if function is None or not callable(function):
            raise AttributeError(
                f"La fonction part{part}() est introuvable."
            )

        captured = io.StringIO()
        start = time.perf_counter()

        with redirect_stdout(captured):
            result = function(raw_data)

        elapsed = time.perf_counter() - start

    finally:
        sys.path.remove(module_path)

    return result, elapsed, captured.getvalue()
