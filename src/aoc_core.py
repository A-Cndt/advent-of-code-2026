def day_dir(day: int) -> Path:
    """Return the folder associated with a day.

    :param day: day number (1-25)
    :type day: int
    :return: path of the ``days/dayXX`` folder
    :rtype: pathlib.Path
    """
    return DAYS_DIR / f"day{day:02d}"


def ensure_day_files(day: int) -> Path:
    """Create the day folder and the ``solution.py`` skeleton if missing.

    :param day: day number
    :type day: int
    :return: path of the day folder
    :rtype: pathlib.Path
    """
    folder = day_dir(day)
    folder.mkdir(parents=True, exist_ok=True)
    solution = folder / SOLUTION_FILE
    if not solution.exists():
        solution.write_text(
            SOLUTION_TEMPLATE.format(day=f"{day:02d}", year=YEAR),
            encoding="utf-8",
        )
    return folder


def ensure_project_layout() -> None:
    """Create the base folders and a ``.gitignore`` if they are missing.

    Called once at startup by ``app.py``. An existing ``.gitignore`` is never
    modified.
    """
    DAYS_DIR.mkdir(exist_ok=True)
    CACHE_DIR.mkdir(exist_ok=True)
    if not GITIGNORE_FILE.exists():
        write_text(GITIGNORE_FILE, GITIGNORE_CONTENT)


def read_text(path: Path) -> str:
    """Read a text file, or return an empty string if it does not exist.

    :param path: path of the file
    :type path: pathlib.Path
    :return: content of the file
    :rtype: str
    """
    return path.read_text(encoding="utf-8") if path.exists() else ""


def write_text(path: Path, content: str) -> None:
    """Write a UTF-8 text file (line endings are left untouched).

    :param path: path of the file
    :type path: pathlib.Path
    :param content: content to write
    :type content: str
    """
    with open(path, "w", encoding="utf-8", newline="") as file:
        file.write(content)


def read_json(path: Path) -> dict:
    """Read a JSON file, or return ``{}`` if it is missing or invalid.

    :param path: path of the JSON file
    :type path: pathlib.Path
    :return: decoded data
    :rtype: dict
    """
    try:
        return json.loads(read_text(path) or "{}")
    except json.JSONDecodeError:
        return {}


def write_json(path: Path, data: dict) -> None:
    """Write a dictionary to an indented JSON file.

    :param path: path of the JSON file
    :type path: pathlib.Path
    :param data: data to serialize
    :type data: dict
    """
    write_text(path, json.dumps(data, indent=2, ensure_ascii=False))


def load_session() -> str:
    """Load the session cookie (environment variable first, then file).

    :return: value of the cookie, or an empty string if it is not set
    :rtype: str
    """
    return os.environ.get("AOC_SESSION") or read_text(SESSION_FILE).strip()


def save_session(session: str) -> None:
    """Save the session cookie into ``.aoc_session``.

    The file is restricted to the current user where the platform supports it.

    :param session: value of the ``session`` cookie
    :type session: str
    """
    write_text(SESSION_FILE, session.strip())
    try:
        SESSION_FILE.chmod(0o600)  # owner read/write only (no-op on Windows)
    except OSError:
        pass


def open_path(path: Path) -> None:
    """Open a file or a folder with the default application.

    For a file, VS Code is used when the ``code`` command is available.

    :param path: file or folder to open
    :type path: pathlib.Path
    """
    code = shutil.which("code")
    if code and path.is_file():
        subprocess.Popen([code, str(path)])
    elif sys.platform.startswith("win"):
        os.startfile(path)  # type: ignore[attr-defined]
    elif sys.platform == "darwin":
        subprocess.Popen(["open", str(path)])
    else:
        subprocess.Popen(["xdg-open", str(path)])


