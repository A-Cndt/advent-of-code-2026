def build_user_agent() -> str:
    """Build the User-Agent header sent to adventofcode.com.

    :return: application identifier and optional contact details
    """
    contact = os.environ.get("AOC_CONTACT", "").strip()

    if contact:
        return f"{USER_AGENT_BASE} ({contact})"

    return USER_AGENT_BASE


def http_get(url: str, session: str | None = None) -> str | Any:
    """Effectue une requête HTTP sécurisée.

    Seuls les protocoles HTTP et HTTPS sont autorisés.

    Args:
        url: URL de la ressource à récupérer.
        session: Jeton de session Advent of Code facultatif.

    Returns:
        Contenu de la réponse HTTP décodé en UTF-8.

    Raises:
        AocError: Si l'URL utilise un protocole non autorisé.
    """
    parsed_url = urllib.parse.urlparse(url)

    if parsed_url.scheme not in {"http", "https"}:
        raise AocError(
            f"Protocole URL non autorisé : {parsed_url.scheme!r}"
        )

    if not parsed_url.netloc:
        raise AocError("URL invalide : nom d'hôte manquant.")

    headers = {
        "User-Agent": USER_AGENT,
    }

    if session:
        headers["Cookie"] = f"session={session}"

    request = urllib.request.Request(
        url,
        headers=headers,
    )

    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return response.read().decode("utf-8")

    except urllib.error.HTTPError as exc:
        raise AocError(
            f"Erreur HTTP {exc.code} lors de la requête."
        ) from exc

    except urllib.error.URLError as exc:
        raise AocError(
            f"Impossible de contacter le serveur : {exc.reason}"
        ) from exc


class PuzzleParser(HTMLParser):
    """Extract the title and the ``<pre>`` blocks of a puzzle page."""

    def __init__(self) -> None:
        """Initialize the parser and its internal buffers."""
        super().__init__(convert_charrefs=True)

        self.title = ""
        self.blocks: list[str] = []

        self._in_pre = False
        self._in_h2 = False

        self._pre_buffer: list[str] = []
        self._h2_buffer: list[str] = []

    def handle_starttag(
        self,
        tag: str,
        attrs: list[tuple[str, str | None]],
    ) -> None:
        """Open a buffer when entering a ``pre`` or ``h2`` tag."""
        if tag == "pre":
            self._in_pre = True
            self._pre_buffer = []

        elif tag == "h2":
            self._in_h2 = True
            self._h2_buffer = []

    def handle_endtag(self, tag: str) -> None:
        """Commit the buffer content when the tag is closed."""
        if tag == "pre" and self._in_pre:
            self._in_pre = False

            block = "".join(self._pre_buffer).strip("\n")

            if block:
                self.blocks.append(block + "\n")

        elif tag == "h2" and self._in_h2:
            self._in_h2 = False

            text = "".join(self._h2_buffer).strip()

            # The title looks like "--- Day 1: Some Title ---".
            if not self.title and ":" in text:
                self.title = text.strip("- ").strip()

    def handle_data(self, data: str) -> None:
        """Feed the buffers with the text found between the tags."""
        if self._in_pre:
            self._pre_buffer.append(data)

        if self._in_h2:
            self._h2_buffer.append(data)


def parse_puzzle(page: str) -> tuple[str, list[str]]:
    """Parse a puzzle page.

    :param page: HTML source of the page
    :return: puzzle title and extracted code blocks
    """
    parser = PuzzleParser()
    parser.feed(page)

    return parser.title, parser.blocks


