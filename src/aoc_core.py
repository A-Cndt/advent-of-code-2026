def day_dir(day: int) -> Path:
    """Return the folder associated with a day.

    :param day: day number (1-25)
    :return: path of the ``days/dayXX`` folder
    """
    if not 1 <= day <= 25:
        raise ValueError("Le jour doit être compris entre 1 et 25.")

    return DAYS_DIR / f"day{day:02d}"


def ensure_day_files(day: int) -> Path:
    """Create the day folder and the ``solution.py`` skeleton if missing.

    :param day: day number
    :return: path of the day folder
    """
    folder = day_dir(day)
    folder.mkdir(parents=True, exist_ok=True)

    solution = folder / SOLUTION_FILE

    if not solution.exists():
        solution.write_text(
            SOLUTION_TEMPLATE.format(day=f"{day:02d}", year=YEAR),
            encoding="utf-8",
        )

    return folder


def ensure_project_layout() -> None:
    """Create the base folders and a ``.gitignore`` if missing."""
    DAYS_DIR.mkdir(parents=True, exist_ok=True)
    CACHE_DIR.mkdir(parents=True, exist_ok=True)

    if not GITIGNORE_FILE.exists():
        write_text(GITIGNORE_FILE, GITIGNORE_CONTENT)


def read_text(path: Path) -> str:
    """Read a text file, or return an empty string if it does not exist.

    :param path: path of the file
    :return: file content
    """
    if not path.exists():
        return ""

    return path.read_text(encoding="utf-8")


def write_text(path: Path, content: str) -> None:
    """Write a UTF-8 text file.

    :param path: path of the file
    :param content: content to write
    """
    with path.open("w", encoding="utf-8", newline="") as file:
        file.write(content)


def read_json(path: Path) -> dict[str, Any]:
    """Read a JSON file, or return an empty dictionary if missing or invalid.

    :param path: path of the JSON file
    :return: decoded JSON object
    """
    try:
        data: Any = json.loads(read_text(path) or "{}")
    except json.JSONDecodeError:
        return {}

    if not isinstance(data, dict):
        return {}

    return data


def write_json(path: Path, data: dict[str, Any]) -> None:
    """Write a dictionary to an indented JSON file.

    :param path: path of the JSON file
    :param data: data to serialize
    """
    write_text(
        path,
        json.dumps(data, indent=2, ensure_ascii=False),
    )


def load_session() -> str:
    """Load the session cookie from the environment or local file.

    :return: session cookie, or an empty string
    """
    return os.environ.get("AOC_SESSION") or read_text(SESSION_FILE).strip()


def save_session(session: str) -> None:
    """Save the session cookie into ``.aoc_session``.

    The file is restricted to the current user where supported.

    :param session: value of the session cookie
    """
    write_text(SESSION_FILE, session.strip())

    with suppress(OSError):
        SESSION_FILE.chmod(0o600)


def open_path(path: Path) -> None:
    """Open a file or folder with the default application.

    VS Code is used for files when the ``code`` command is available.

    :param path: path to open
    """
    code = shutil.which("code")

    if code and path.is_file():
        subprocess.Popen([code, str(path)])
    elif sys.platform.startswith("win"):
        os.startfile(path)  # type: ignore[attr-defined]
    elif sys.platform == "darwin":
        subprocess.Popen(["open", str(path)])
    else:
        subprocess.Popen(["xdg-open", str(path)])


